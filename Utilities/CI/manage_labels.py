"""Generate PR path rules and upsert managed repository labels using gh.

Status, Change and Review labels have metadata but no automatic path rules.
Synchronization never deletes labels or changes labels on existing issues/PRs.
"""

import argparse
import json
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path(".github/labels.json")
RULES = Path(".github/labeler.yml")
MODULE_ROOTS = (
    "Source/Engine", "Source/Editor", "Source/EnginePlugins",
    "Source/EditorPlugins", "Source/Tools/Libs",
)


def discover_modules(root):
    modules = {path.relative_to(root).as_posix()
               for parent in MODULE_ROOTS
               for path in (root / parent).iterdir() if path.is_dir()}
    modules.add("Source/UnitTests/TestFramework")
    return modules


def validate(catalog, root):
    names = set()
    covered = set()
    for label in catalog:
        if set(label) not in ({"name", "color", "description", "paths"}, {"name", "color", "description"}):
            raise ValueError("Labels require name, color, description and optional paths")
        name = label["name"]
        if not isinstance(name, str) or not name or len(name) > 50 or name.casefold() in names:
            raise ValueError(f"Invalid or duplicate label name: {name}")
        if not (name == "GitHub" or name.startswith(("Area: ", "Module: ", "Status: ", "Change: ", "Review: "))):
            raise ValueError(f"Unmanaged label category: {name}")
        names.add(name.casefold())
        if not re.fullmatch(r"[0-9a-fA-F]{6}", label["color"]):
            raise ValueError(f"Invalid label color: {name}")
        if not isinstance(label["description"], str) or not 0 < len(label["description"]) <= 100:
            raise ValueError(f"Invalid label description: {name}")
        if name.startswith(("Status: ", "Change: ", "Review: ")):
            if "paths" in label:
                raise ValueError(f"Manual label must not have automatic path rules: {name}")
            continue
        paths = label.get("paths")
        if not isinstance(paths, list) or not paths or len(paths) != len(set(paths)):
            raise ValueError(f"Empty or duplicate paths: {name}")
        for pattern in paths:
            if not isinstance(pattern, str) or not pattern or pattern.startswith(("!", "/")) or "\\" in pattern or ".." in pattern.split("/"):
                raise ValueError(f"Invalid repository glob: {pattern}")
            # Literal directory rules must refer to real directories. This catches
            # renamed modules and obsolete paths without interpreting minimatch.
            if pattern.endswith("/**") and not re.search(r"[*?{[!]", pattern[:-3]):
                if not (root / pattern[:-3]).is_dir():
                    raise ValueError(f"Missing directory: {pattern}")
                if name.startswith("Module: "):
                    covered.add(pattern[:-3])
    missing = discover_modules(root) - covered
    if missing:
        raise ValueError("Modules missing dedicated label rules: " + ", ".join(sorted(missing)))


def render(catalog):
    lines = ["# Generated by Utilities/CI/manage_labels.py generate; edit .github/labels.json.", ""]
    for label in catalog:
        if "paths" not in label:
            continue
        lines += [json.dumps(label["name"]) + ":", "  - changed-files:", "      - any-glob-to-any-file:"]
        lines += ["          - " + json.dumps(path) for path in label["paths"]]
        lines.append("")
    return "\n".join(lines)


def gh(*args):
    result = subprocess.run(["gh", *args], check=True, text=True, capture_output=True)
    return result.stdout


def get_labels(repo):
    return json.loads(gh("label", "list", "--repo", repo, "--limit", "1000", "--json", "name,color,description"))


def pending_labels(catalog, existing):
    current = {label["name"].casefold(): label for label in existing}
    return [label for label in catalog
            if (old := current.get(label["name"].casefold())) is None
            or old["color"].lower() != label["color"].lower()
            or old["description"] != label["description"]]


def synchronize(catalog, repo, apply):
    pending = pending_labels(catalog, get_labels(repo))
    for label in pending:
        print(f"{'Upsert' if apply else 'Would upsert'} {label['name']}")
        if apply:
            gh("label", "create", label["name"], "--repo", repo,
               "--color", label["color"], "--description", label["description"], "--force")
    if apply and pending_labels(catalog, get_labels(repo)):
        raise RuntimeError("Repository labels do not match the catalog after synchronization")
    print(f"{len(pending)} label(s) {'synchronized' if apply else 'would change'}; {len(catalog)} managed labels.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("check", "generate", "sync"))
    parser.add_argument("--repo", help="Explicit OWNER/REPO destination for synchronization")
    parser.add_argument("--apply", action="store_true", help="Apply synchronization; otherwise only show changes")
    args = parser.parse_args()
    if args.command == "sync" and not args.repo:
        parser.error("sync requires --repo OWNER/REPO")
    if args.command != "sync" and (args.repo or args.apply):
        parser.error("--repo and --apply are only valid with sync")
    catalog = json.loads((ROOT / CATALOG).read_text(encoding="utf-8"))
    validate(catalog, ROOT)
    if args.command == "generate":
        (ROOT / RULES).write_text(render(catalog), encoding="utf-8", newline="\n")
    elif args.command == "check":
        if (ROOT / RULES).read_text(encoding="utf-8") != render(catalog):
            raise SystemExit("Labeler rules are stale: run python Utilities/CI/manage_labels.py generate")
        path_count = sum("paths" in label for label in catalog)
        print(f"Label metadata, module coverage and generated rules passed ({len(catalog)} labels; {path_count} path rules).")
    else:
        synchronize(catalog, args.repo, args.apply)


if __name__ == "__main__":
    main()
